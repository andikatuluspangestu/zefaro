//! PHP version management: discover official Windows builds, install them into
//! `~/.config/zefaro/bin/php/<minor>`, keep a Zefaro-managed block in each php.ini,
//! and expose the active version on the command line through `bin\php.bat`.
//!
//! Builds come from the official Windows distribution at
//! downloads.php.net/~windows (windows.php.net now redirects there). Zefaro uses
//! the NTS x64 zips — they pair with nginx through php-cgi's FastCGI listener —
//! and checks every download against the SHA-256 published in releases.json.

use crate::engine::supervisor::{Probe, Spec};
use crate::engine::{net, paths, process};
use crate::error::{AppError, AppResult};
use crate::model::{InstallProgress, PhpLimits, PhpVersion};
use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

pub const RELEASES_URL: &str = "https://downloads.php.net/~windows/releases/releases.json";
const DOWNLOAD_BASE: &str = "https://downloads.php.net/~windows/releases/";
const CACERT_URL: &str = "https://curl.se/ca/cacert.pem";

/// Oldest line Zefaro offers.
const OLDEST: (u32, u32) = (7, 4);
/// Written next to php.exe with the exact patch version that was installed.
const VERSION_MARKER: &str = ".zefaro-version";
/// Everything after this line in php.ini is regenerated by Zefaro; anything the
/// user writes above it is preserved.
pub const INI_MARKER: &str =
    "; ---- Managed by Zefaro: everything below is regenerated, edit above this line ----";

/// Extensions on by default whenever the build ships their DLL. GD is php_gd.dll
/// on PHP 8 and php_gd2.dll on 7.4; OPcache is a DLL up to 8.4 and built in from
/// 8.5.
const EXTENSIONS: &[&str] = &[
    "bz2", "curl", "exif", "fileinfo", "gd", "gd2", "gettext", "intl", "mbstring", "mysqli",
    "opcache", "openssl", "pdo_mysql", "pdo_pgsql", "pdo_sqlite", "pgsql", "sodium", "sqlite3",
    "xsl", "zip",
];
/// Loaded with `zend_extension=` rather than `extension=`.
const ZEND_EXTENSIONS: &[&str] = &["opcache", "xdebug"];

/// Xdebug for Windows (NTS, x64), one build per PHP line: (line, Xdebug
