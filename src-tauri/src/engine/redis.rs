//! Redis — cache, queues and sessions. Listens on 127.0.0.1:6379 and
//! persists to an RDB snapshot.
//!
//! Redis has no official Windows build; Zefaro uses the redis-windows project's
//! build of upstream Redis (msys2 flavour). That build treats `C:/…` as a
//! relative path, so the config only uses paths relative to its working
//! directory — never absolute Windows paths.

use crate::engine::archive::{self, Archive};
use crate::engine::paths;
use crate::engine::supervisor::{Probe, Spec};
use crate::error::AppResult;
use std::fs;
use std::path::{Path, PathBuf};

pub const VERSION: &str = "8.10.2";
pub const SERVICE_ID: &str = "redis";
pub const PORT: u16 = 6379;
pub const DOWNLOAD_MB: u32 = 14;

/// Redis-8.10.2-Windows-x64-msys2.zip from github.com/redis-windows/redis-windows;
/// SHA-256 = the digest GitHub publishes for the release asset.
const ARCHIVE: Archive = Archive {
    name: "Redis 8.10.2",
    url: "https://github.com/redis-windows/redis-windows/releases/download/8.10.2/Redis-8.10.2-Windows-x64-msys2.zip",
    sha256: "7c8cebd50347eaa1d9e784da842ed47a4f33394637835531d6614777b950ee85",
    inner: "Redis-8.10.2-Windows-x64-msys2",
};

#[derive(Clone, Debug)]
pub struct Layout {
    /// Binary distribution (redis-server.exe, redis-cli.exe).
    pub base: PathBuf,
    /// Working directory: redis.conf and data/.
    pub home: PathBuf,
    pub log: PathBuf,
    pub port: u16,
}

impl Layout {
    pub fn standard() -> Self {
        Self {
            base: paths::bin_dir().join("redis"),
            home: crate::config::config_dir().join("redis"),
            log: paths::logs_dir().join("redis.log"),
            port: PORT,
        }
    }
}

pub fn installed(l: &Layout) -> bool {
    l.base.join("redis-server.exe").is_file()
}

/// Only relative paths (see the module docs). Snapshots: after an hour with
/// one change, five minutes with 100, or a minute with 10,000.
pub fn render_conf(port: u16) -> String {
    format!(
        "# Generated by Zefaro — rewritten on every start, do not edit.\n\
         port {port}\n\
         bind 127.0.0.1\n\
         protected-mode yes\n\
         dir data\n\
         dbfilename dump.rdb\n\
         logfile \"\"\n\
         save 3600 1 300 100 60 10000\n"
    )
}

/// Install on first use and write redis.conf. Serialized against concurrent starts.
pub fn prepare(l: &Layout, scratch: &Path, keep_zip: bool) -> AppResult<()> {
    archive::exclusive(&l.base, || {
        if !installed(l) {
            ARCHIVE.install(&l.base, scratch, keep_zip)?;
        }
        fs::create_dir_all(l.home.join("data"))?;
        fs::write(l.home.join("redis.conf"), render_conf(l.port))?;
        Ok(())
    })
}

pub fn spec(l: &Layout) -> Spec {
    Spec {
        id: SERVICE_ID.into(),
        program: l.base.join("redis-server.exe"),
        args: vec!["redis.conf".into()],
        cwd: l.home.clone(),
        env: Vec::new(),
        log: l.log.clone(),
        port: l.port,
        probe: Probe::Tcp,
        // SHUTDOWN saves a final snapshot before exiting.
        stop: Some((
            l.base.join("redis-cli.exe"),
            vec!["-p".into(), l.port.to_string().into(), "SHUTDOWN".into()],
        )),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn config_uses_only_relative_paths() {
        let conf = render_conf(6379);
        assert!(conf.contains("port 6379\n"));
        assert!(conf.contains("bind 127.0.0.1\n"));
        assert!(conf.contains("dir data\n"));
        assert!(!conf.contains(":/") && !conf.contains(":\\"), "no absolute Windows paths:\n{conf}");
    }
}
