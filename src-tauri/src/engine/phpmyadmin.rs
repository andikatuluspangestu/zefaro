//! phpMyAdmin — the database GUI, served by Zefaro's nginx at
//! `phpmyadmin.<tld>` and run by an installed PHP line it supports. It signs
//! in automatically as MariaDB's root user (local development only: nginx and
//! MariaDB both listen on 127.0.0.1 alone).

use crate::engine::archive::{self, Archive};
use crate::engine::{paths, php};
use crate::error::AppResult;
use sha2::{Digest, Sha256};
use std::fs;
use std::path::{Path, PathBuf};

pub const VERSION: &str = "5.2.3";
pub const SERVICE_ID: &str = "phpmyadmin";
/// Site name: served at `phpmyadmin.<tld>`.
pub const HOST: &str = "phpmyadmin";
pub const DOWNLOAD_MB: u32 = 16;

/// phpMyAdmin 5.2.3 supports PHP >= 7.2 and < 8.4 (phpmyadmin.net's
/// version.json).
const PHP_MIN: (u32, u32) = (7, 2);
const PHP_BELOW: (u32, u32) = (8, 4);
/// Experimental: 8.4 and 8.5 aren't supported by 5.2.3, but it opened, ran
/// queries and exported on 8.4. Used only when no supported line is installed.
const PHP_TRIAL_BELOW: (u32, u32) = (8, 6);
pub const PHP_RANGE: &str = "7.2 to 8.5";
/// `PHP_RANGE` in Indonesian, for the interface's messages.
pub const PHP_RANGE_ID: &str = "7.2 sampai 8.5";

/// phpMyAdmin-5.2.3-all-languages.zip; SHA-256 pinned after verifying its PGP
/// signature (Isaac Bennetch, 3D06 A59E CE73 0EB7 1B51 1C17 CE75 2F17 8259 BD92)
/// and matching files.phpmyadmin.net's .sha256.
const ARCHIVE: Archive = Archive {
    name: "phpMyAdmin 5.2.3",
    url: "https://files.phpmyadmin.net/phpMyAdmin/5.2.3/phpMyAdmin-5.2.3-all-languages.zip",
    sha256: "2d2e13c735366d318425c78e4ee2cc8fc648d77faba3ddea2cd516e43885733f",
    inner: "phpMyAdmin-5.2.3-all-languages",
};

pub fn dir() -> PathBuf {
    paths::apps_dir().join("phpmyadmin")
}

pub fn installed_at(dir: &Path) -> bool {
    dir.join("index.php").is_file()
}

/// Newest installed PHP line phpMyAdmin supports; failing that, the oldest
/// experimental one (8.4 before 8.5).
pub fn pick_php(installed: &[String]) -> Option<String> {
    let supported = installed
        .iter()
        .filter(|m| php::minor_key(m).is_some_and(|k| k >= PHP_MIN && k < PHP_BELOW))
        .max_by_key(|m| php::minor_key(m));
    let trial = || {
        installed
            .iter()
            .filter(|m| is_experimental(m))
            .min_by_key(|m| php::minor_key(m))
    };
    supported.or_else(trial).cloned()
}

/// A PHP line phpMyAdmin only runs on as an experiment (8.4, 8.5).
pub fn is_experimental(minor: &str) -> bool {
    php::minor_key(minor).is_some_and(|k| k >= PHP_BELOW && k < PHP_TRIAL_BELOW)
}

pub fn render_config(secret: &str, db_port: u16, tmp: &Path) -> String {
    let tmp = tmp.display().to_string().replace('\\', "/");
    format!(
        r#"<?php
// Generated by Zefaro. Local development only: signs in to MariaDB as root,
// which has no password and only listens on 127.0.0.1.
$cfg['blowfish_secret'] = '{secret}';

$i = 1;
$cfg['Servers'][$i]['auth_type'] = 'config';
$cfg['Servers'][$i]['host'] = '127.0.0.1';
$cfg['Servers'][$i]['port'] = '{db_port}';
$cfg['Servers'][$i]['user'] = 'root';
$cfg['Servers'][$i]['password'] = '';
$cfg['Servers'][$i]['AllowNoPassword'] = true;

$cfg['TempDir'] = '{tmp}';
$cfg['UploadDir'] = '';
$cfg['SaveDir'] = '';
$cfg['VersionCheck'] = false;
$cfg['SendErrorReports'] = 'never';
"#
    )
}

/// 32 characters for blowfish_secret (phpMyAdmin wants exactly 32 bytes).
/// Only used to encrypt phpMyAdmin's own cookies on this machine.
fn new_secret() -> String {
    let seed = format!(
        "{:?}|{}|{:p}",
        std::time::SystemTime::now(),
        std::process::id(),
        &PHP_MIN
    );
    format!("{:x}", Sha256::digest(seed.as_bytes()))[..32].to_owned()
}

/// Read by php-cgi for scripts in phpMyAdmin's folder only: hides the
/// deprecation notices newer PHP lines raise in 5.2.3's code.
const USER_INI: &str = "; Generated by Zefaro.
error_reporting = E_ALL & ~E_DEPRECATED & ~E_USER_DEPRECATED
";

/// Install on first use and write config.inc.php once (keeping its secret).
/// Serialized against concurrent starts.
pub fn prepare(dir: &Path, db_port: u16, scratch: &Path, keep_zip: bool) -> AppResult<()> {
    archive::exclusive(dir, || {
        if !installed_at(dir) {
            ARCHIVE.install(dir, scratch, keep_zip)?;
        }
        let tmp = dir.join("tmp");
        fs::create_dir_all(&tmp)?;
        let config = dir.join("config.inc.php");
        if !config.is_file() {
            fs::write(config, render_config(&new_secret(), db_port, &tmp))?;
        }
        fs::write(dir.join(".user.ini"), USER_INI)?;
        Ok(())
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn lines(v: &[&str]) -> Vec<String> {
        v.iter().map(|s| s.to_string()).collect()
    }

    #[test]
    fn picks_newest_supported_php_line() {
        assert_eq!(pick_php(&lines(&["8.5", "8.4", "8.3", "8.2"])).as_deref(), Some("8.3"));
        assert_eq!(pick_php(&lines(&["7.4", "8.0"])).as_deref(), Some("8.0"));
        assert_eq!(pick_php(&lines(&["7.1"])), None, "older than 7.2");
        assert_eq!(pick_php(&lines(&[])), None);
    }

    #[test]
    fn falls_back_to_experimental_lines() {
        assert_eq!(pick_php(&lines(&["8.5", "8.4"])).as_deref(), Some("8.4"));
        assert_eq!(pick_php(&lines(&["8.5"])).as_deref(), Some("8.5"));
        assert_eq!(pick_php(&lines(&["8.6"])), None, "past the trial range");
        assert!(is_experimental("8.4") && is_experimental("8.5"));
        assert!(!is_experimental("8.3") && !is_experimental("8.6"));
    }

    fn http_get(port: u16, host: &str) -> String {
        use std::io::{Read, Write};
        let mut s = std::net::TcpStream::connect(("127.0.0.1", port)).unwrap();
        write!(s, "GET / HTTP/1.1\r\nHost: {host}\r\nConnection: close\r\n\r\n").unwrap();
        let mut body = String::new();
        s.read_to_string(&mut body).unwrap();
        body
    }

    fn redis_cmd(port: u16, cmd: &str) -> String {
        use std::io::{BufRead, BufReader, Write};
        let mut s = std::net::TcpStream::connect(("127.0.0.1", port)).unwrap();
        write!(s, "{cmd}\r\n").unwrap();
        let mut line = String::new();
        BufReader::new(s).read_line(&mut line).unwrap();
        line.trim().to_owned()
    }

    /// MariaDB, Redis and phpMyAdmin (via nginx + PHP 8.3's php-cgi) on spare
    /// ports in a temp folder. Downloads are cached in %TEMP%\zefaro-test-cache.
    #[test]
    #[ignore = "network (~125 MB, cached) + needs PHP 8.3 installed by Zefaro (run with --ignored)"]
    fn live_mariadb_redis_and_phpmyadmin() {
        use crate::config::ZefaroConfig;
        use crate::engine::supervisor::{port_open, Supervisor};
        use crate::engine::{mariadb, nginx, redis};

        assert!(php::is_installed("8.3"), "install PHP 8.3 in Zefaro first");
        let cache = std::env::temp_dir().join("zefaro-test-cache");
        fs::create_dir_all(&cache).unwrap();
        let tmp = std::env::temp_dir().join(format!("zefaro-db-live-{}", std::process::id()));
        let _ = fs::remove_dir_all(&tmp);
        let sup = Supervisor::default();

        let m = mariadb::Layout {
            base: tmp.join("mariadb"),
            data: tmp.join("data").join("mariadb"),
            conf: tmp.join("mariadb-conf").join("my.ini"),
            log: tmp.join("logs").join("mariadb.log"),
            port: 3317,
        };
        mariadb::prepare(&m, &cache, true).expect("install + init MariaDB");
        sup.start(mariadb::spec(&m)).expect("start MariaDB");
        let who = mariadb::query(&m, "CREATE DATABASE zefaro_test; SELECT CURRENT_USER();").unwrap();
        assert!(who.contains("root@localhost"), "{who}");

        let r = redis::Layout {
            base: tmp.join("redis"),
            home: tmp.join("redis-home"),
            log: tmp.join("logs").join("redis.log"),
            port: 6389,
        };
        redis::prepare(&r, &cache, true).expect("install Redis");
        sup.start(redis::spec(&r)).expect("start Redis");
        assert_eq!(redis_cmd(6389, "PING"), "+PONG");

        let pma = tmp.join("phpmyadmin");
        prepare(&pma, 3317, &cache, true).expect("install phpMyAdmin");
        let mut l = nginx::Layout::under(tmp.join("nginx-bin"), tmp.join("nginx"), tmp.join("logs"), 8097);
        l.phpmyadmin = pma.clone();
        nginx::install_to(&l.nginx, &cache).expect("install nginx");
        let mut cfg = ZefaroConfig::default();
        cfg.sites.clear();
        cfg.phpmyadmin = true;
        cfg.default_php = "8.3".into();
        cfg.php.base_port = 9597 - 83; // PHP 8.3 → 9597
        nginx::write_config(&cfg, &l).unwrap();
        nginx::test_config(&l).expect("nginx -t");
        let mut cgi = php::cgi_spec("8.3", 9597);
        cgi.log = tmp.join("logs").join("php-8.3.log");
        sup.start(cgi.clone()).expect("start php-cgi");
        sup.start(nginx::spec(&l)).expect("start nginx");

        let page = http_get(8097, "phpmyadmin.test");
        let head = &page[..page.len().min(600)];
        assert!(page.starts_with("HTTP/1.1 200"), "{head}");
        // Signed in automatically: the home page shows the server version.
        assert!(page.contains("11.8.9-MariaDB"), "not signed in to MariaDB:\n{head}");

        for id in [nginx::SERVICE_ID, cgi.id.as_str(), redis::SERVICE_ID, mariadb::SERVICE_ID] {
            sup.stop(id).unwrap();
        }
        std::thread::sleep(std::time::Duration::from_millis(500));
        for port in [8097, 9597, 6389, 3317] {
            assert!(!port_open(port), "port {port} still open after stop");
        }
        let mlog = fs::read_to_string(&m.log).unwrap_or_default();
        assert!(mlog.contains("Shutdown complete"), "MariaDB didn't shut down cleanly");
        assert!(r.home.join("data").join("dump.rdb").is_file(), "Redis saved on SHUTDOWN");
        let _ = fs::remove_dir_all(&tmp);
    }

    #[test]
    fn config_signs_in_as_local_root() {
        let conf = render_config("x".repeat(32).as_str(), 3306, Path::new(r"C:\zefaro\apps\phpmyadmin\tmp"));
        assert!(conf.contains("$cfg['Servers'][$i]['auth_type'] = 'config';"));
        assert!(conf.contains("$cfg['Servers'][$i]['host'] = '127.0.0.1';"));
        assert!(conf.contains("$cfg['Servers'][$i]['port'] = '3306';"));
        assert!(conf.contains("$cfg['TempDir'] = 'C:/zefaro/apps/phpmyadmin/tmp';"));
        assert_eq!(new_secret().len(), 32);
    }
}
