//! Adminer: one PHP file that browses MariaDB, MySQL and PostgreSQL alike,
//! served by Zefaro's nginx at `adminer.<tld>`. phpMyAdmin only speaks to
//! MariaDB; Adminer fills in for MySQL and PostgreSQL.
//!
//! Adminer refuses empty passwords unless told otherwise, and root has none on
//! Zefaro's servers (they listen on 127.0.0.1 only). Zefaro's `index.php` wraps
//! adminer.php with an `adminer_object()` that accepts them, and opens on a
//! page that lists the three servers. Each link opens Adminer's own login form
//! filled in; Login (with its CSRF token intact) signs in.

use crate::engine::{mariadb, mysql, net, paths, php, postgres, progress};
use crate::error::{AppError, AppResult};
use std::fs;
use std::path::{Path, PathBuf};

pub const VERSION: &str = "6.3.0";
pub const SERVICE_ID: &str = "adminer";
/// Site name: served at `adminer.<tld>`.
pub const HOST: &str = "adminer";
pub const DOWNLOAD_KB: u32 = 571;
/// adminer-6.3.0.php (every driver, every language) from Adminer's GitHub
/// release; the SHA-256 is GitHub's digest of that asset.
const URL: &str = "https://github.com/vrana/adminer/releases/download/v6.3.0/adminer-6.3.0.php";
const SHA256: &str = "641e1a31e8cc333a309e202ef9446e1fd38c2069ed5f9ee509b80d70089d0503";
/// Adminer 6 uses typed properties: PHP 7.4 or later.
const PHP_MIN: (u32, u32) = (7, 4);

pub fn dir() -> PathBuf {
    paths::apps_dir().join("adminer")
}

pub fn installed_at(dir: &Path) -> bool {
    dir.join("adminer.php").is_file()
}

/// The active PHP line when it's installed and new enough, else the newest installed one.
pub fn pick_php(active: &str, installed: &[String]) -> Option<String> {
    let ok = |m: &str| php::minor_key(m).is_some_and(|k| k >= PHP_MIN);
    if installed.iter().any(|m| m == active) && ok(active) {
        return Some(active.to_owned());
    }
    installed.iter().filter(|m| ok(m)).max_by_key(|m| php::minor_key(m)).cloned()
}

/// One of Zefaro's servers, as Adminer's URL names it.
pub struct Server {
    pub name: &'static str,
    /// Adminer's driver key in the URL: `server` (MySQL and MariaDB) or `pgsql`.
    pub driver: &'static str,
    pub port: u16,
}

pub const SERVERS: [Server; 3] = [
    Server { name: "MariaDB", driver: "server", port: mariadb::PORT },
    Server { name: "MySQL", driver: "server", port: mysql::PORT },
    Server { name: "PostgreSQL", driver: "pgsql", port: postgres::PORT },
];

/// The query that opens Adminer's login form filled in for a server.
pub fn query(server: &Server) -> String {
    let user = if server.driver == "pgsql" { postgres::USER } else { "root" };
    format!("?{}=127.0.0.1:{}&username={user}", server.driver, server.port)
}

/// The Zefaro server a site's database is on, by its port.
pub fn server_for(postgres: bool, port: u16) -> Option<&'static Server> {
    SERVERS.iter().find(|s| (s.driver == "pgsql") == postgres && s.port == port)
}

/// Adminer at one database: `base` is `http://adminer.test`.
pub fn database_url(base: &str, server: &Server, db: &str) -> String {
    let mut url = format!("{base}/{}", query(server));
    if !db.is_empty() {
        url.push_str("&db=");
        url.push_str(&db.replace('&', "%26").replace(' ', "%20"));
    }
    url
}

/// Zefaro's index.php: the server list when opened bare, Adminer otherwise.
