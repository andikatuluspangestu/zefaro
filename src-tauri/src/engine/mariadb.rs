//! MariaDB LTS — the MySQL-compatible database. Listens on 127.0.0.1:3306
//! with `root` and no password, the usual local-development setup (and what a
//! fresh Laravel `.env` expects).

use crate::engine::archive::{self, Archive};
use crate::engine::supervisor::{Probe, Spec};
use crate::engine::{paths, process};
use crate::error::{AppError, AppResult};
use std::fs;
use std::path::{Path, PathBuf};

pub const VERSION: &str = "11.8.9";
pub const SERVICE_ID: &str = "mariadb";
pub const PORT: u16 = 3306;
pub const DOWNLOAD_MB: u32 = 93;

/// mariadb-11.8.9-winx64.zip; SHA-256 pinned after verifying its PGP signature
/// (MariaDB Signing Key 177F 4010 FE56 CA33 3630 0305 F165 6F24 C74C D1D8). It
/// also matches the checksum in downloads.mariadb.org's release API.
const ARCHIVE: Archive = Archive {
    name: "MariaDB 11.8.9",
    url: "https://archive.mariadb.org/mariadb-11.8.9/winx64-packages/mariadb-11.8.9-winx64.zip",
    sha256: "830c46727d9278eae212ae3eca44eeb9e71b2a68704e95f344a64fba7b1963f5",
    inner: "mariadb-11.8.9-winx64",
};

#[derive(Clone, Debug)]
pub struct Layout {
    /// Binary distribution (bin/mariadbd.exe, …).
    pub base: PathBuf,
    /// Data directory (system tables + your databases).
    pub data: PathBuf,
    /// Zefaro's generated my.ini.
    pub conf: PathBuf,
    pub log: PathBuf,
    pub port: u16,
}

impl Layout {
    pub fn standard() -> Self {
        Self {
            base: paths::bin_dir().join("mariadb"),
            data: paths::data_dir().join("mariadb"),
            conf: crate::config::config_dir().join("mariadb").join("my.ini"),
            log: paths::logs_dir().join("mariadb.log"),
            port: PORT,
        }
    }

    fn bin(&self, exe: &str) -> PathBuf {
        self.base.join("bin").join(exe)
    }
}

pub fn installed(l: &Layout) -> bool {
    l.bin("mariadbd.exe").is_file()
}

fn initialized(l: &Layout) -> bool {
    l.data.join("mysql").is_dir()
}

/// Create the system tables (once). root@localhost gets no password; the
/// server only ever listens on 127.0.0.1.
fn initialize(l: &Layout) -> AppResult<()> {
    if l.data.is_dir() && fs::read_dir(&l.data)?.next().is_some() {
        let data = l.data.display();
        return Err(AppError::msg(crate::tr!(
            format!(
                "{data} has files in it but no MariaDB system tables. Move the folder somewhere else and start MariaDB again."
            ),
            format!(
                "{data} berisi file tetapi tidak punya tabel sistem MariaDB. Pindahkan folder itu ke tempat lain, lalu mulai MariaDB lagi."
            )
        )));
    }
    if let Some(parent) = l.data.parent() {
        fs::create_dir_all(parent)?;
    }
    process::run(process::command(l.bin("mariadb-install-db.exe")).arg(format!("--datadir={}", l.data.display())))
        .map(|_| ())
        .map_err(|e| {
            AppError::msg(crate::tr!(
                format!("Zefaro couldn't create the MariaDB data folder: {e}"),
                format!("Zefaro tidak dapat membuat folder data MariaDB: {e}")
            ))
        })
}

fn fwd(p: &Path) -> String {
    p.display().to_string().replace('\\', "/")
}

pub fn render_ini(l: &Layout) -> String {
    format!(
        r#"# Generated by Zefaro — rewritten on every start, do not edit.
[mysqld]
basedir="{base}"
datadir="{data}"
port={port}
bind-address=127.0.0.1
character-set-server=utf8mb4
collation-server=utf8mb4_unicode_ci
# Modest memory use for a development machine.
innodb_buffer_pool_size=128M
# Large rows and long multi-row INSERTs in big dumps. Memory is only used
# when a packet that large actually arrives.
max_allowed_packet=1G
# Write the redo log at each commit but flush it to disk about once a second:
# much faster imports. A power cut could lose the last second of writes —
# fine for local development, never for a production server.
innodb_flush_log_at_trx_commit=2
# Zefaro's health check connects without logging in every few seconds; at the
# default level (2) each check adds two "Aborted connection" warnings.
log_warnings=1

[client]
host=127.0.0.1
port={port}
"#,
        base = fwd(&l.base),
        data = fwd(&l.data),
        port = l.port,
    )
}

/// Install on first use, write my.ini, and create the data folder once.
/// `scratch` holds the download; tests keep the zip to avoid re-downloading.
/// Serialized, so concurrent starts can't install or initialise twice.
pub fn prepare(l: &Layout, scratch: &Path, keep_zip: bool) -> AppResult<()> {
    archive::exclusive(&l.base, || {
        if !installed(l) {
            ARCHIVE.install(&l.base, scratch, keep_zip)?;
        }
        if let Some(dir) = l.conf.parent() {
            fs::create_dir_all(dir)?;
        }
        fs::write(&l.conf, render_ini(l))?;
        if !initialized(l) {
            initialize(l)?;
        }
        Ok(())
    })
}

pub fn spec(l: &Layout) -> Spec {
    Spec {
        id: SERVICE_ID.into(),
        program: l.bin("mariadbd.exe"),
        // --defaults-file must come first; --console sends the server log to
        // stderr, i.e. into Zefaro's mariadb.log.
        args: vec![format!("--defaults-file={}", l.conf.display()).into(), "--console".into()],
        cwd: l.base.clone(),
        env: Vec::new(),
        log: l.log.clone(),
        port: l.port,
        probe: Probe::Tcp,
        // A clean shutdown flushes InnoDB instead of forcing crash recovery.
        stop: Some((
            l.bin("mariadb-admin.exe"),
            vec![
                "-h".into(),
                "127.0.0.1".into(),
                "-P".into(),
                l.port.to_string().into(),
                "-u".into(),
                "root".into(),
                "shutdown".into(),
            ],
        )),
    }
}

/// Run SQL as root through the bundled client; returns its output.
#[cfg(test)]
pub fn query(l: &Layout, sql: &str) -> AppResult<String> {
    process::run(process::command(l.bin("mariadb.exe")).args([
        "-h",
        "127.0.0.1",
        "-P",
        &l.port.to_string(),
        "-u",
        "root",
        "--batch",
        "--skip-column-names",
        "-e",
        sql,
    ]))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ini_binds_loopback_with_forward_slash_paths() {
        let l = Layout {
            base: PathBuf::from(r"C:\zefaro\bin\mariadb"),
            data: PathBuf::from(r"C:\zefaro\data\mariadb"),
            conf: PathBuf::from(r"C:\zefaro\mariadb\my.ini"),
            log: PathBuf::from(r"C:\zefaro\logs\mariadb.log"),
            port: 3306,
        };
        let ini = render_ini(&l);
        assert!(ini.contains("bind-address=127.0.0.1"));
        assert!(ini.contains("port=3306"));
        assert!(ini.contains(r#"datadir="C:/zefaro/data/mariadb""#));
        assert!(ini.contains("character-set-server=utf8mb4"));
        let spec = spec(&l);
        assert_eq!(spec.args[0], r"--defaults-file=C:\zefaro\mariadb\my.ini", "must be the first argument");
        assert!(spec.stop.unwrap().1.iter().any(|a| a == "shutdown"));
    }
}
