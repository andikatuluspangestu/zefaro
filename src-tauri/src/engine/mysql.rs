//! MySQL LTS. Listens on 127.0.0.1:3307 with `root` and no password, next to
//! MariaDB on 3306, so a project can use either and both can run at once.
//!
//! Oracle's Windows zip unpacks to 1.4 GB, most of it debug symbols. Zefaro
//! leaves out what the server and its clients don't run: see [`wanted`].

use crate::engine::archive::{self, Archive};
use crate::engine::supervisor::{Probe, Spec};
use crate::engine::{paths, process};
use crate::error::{AppError, AppResult};
use std::fs;
use std::path::{Path, PathBuf};

pub const VERSION: &str = "9.7.4";
pub const SERVICE_ID: &str = "mysql";
/// 3306 belongs to MariaDB.
pub const PORT: u16 = 3307;
pub const DOWNLOAD_MB: u32 = 328;

/// mysql-9.7.4-winx64.zip from dev.mysql.com. Oracle publishes only an MD5
/// for it; the download matched the MD5 on the download page
/// (e05aaa40639d8548e0f68b7a70685a3b) before its SHA-256 was recorded here.
const ARCHIVE: Archive = Archive {
    name: "MySQL 9.7.4",
    url: "https://dev.mysql.com/get/Downloads/MySQL-9.7/mysql-9.7.4-winx64.zip",
    sha256: "641bdaf01004927194c561b956f14f915a3166c9b0f9b1b5464ae63152bf4b96",
    inner: "mysql-9.7.4-winx64",
};

/// What Zefaro unpacks from the zip (`rel` is relative to its top folder).
/// Left out: debug symbols (.pdb, 840 MB), import and static libraries (.lib),
/// the debug build of the plugins, the MeCab dictionaries (125 MB, only for
/// Japanese full-text search), the C headers and the docs.
fn wanted(rel: &Path) -> bool {
    let ext = rel.extension().map(|e| e.to_ascii_lowercase());
    let under = |dir: &str| rel.starts_with(dir);
    !(ext.as_ref().is_some_and(|e| e == "pdb" || e == "lib")
        || under("include")
        || under("docs")
        || under("lib/mecab")
        || under("lib/plugin/debug"))
}

#[derive(Clone, Debug)]
pub struct Layout {
    /// bin/mysqld.exe, lib, share.
    pub base: PathBuf,
    pub data: PathBuf,
    /// Zefaro's generated my.ini.
    pub conf: PathBuf,
    pub log: PathBuf,
    pub port: u16,
}

impl Layout {
    pub fn standard() -> Self {
        Self {
            base: paths::bin_dir().join("mysql"),
            data: paths::data_dir().join("mysql"),
            conf: crate::config::config_dir().join("mysql").join("my.ini"),
            log: paths::logs_dir().join("mysql.log"),
            port: PORT,
        }
    }

    pub fn bin(&self, exe: &str) -> PathBuf {
        self.base.join("bin").join(exe)
    }
}

pub fn installed(l: &Layout) -> bool {
    l.bin("mysqld.exe").is_file()
}

fn initialized(l: &Layout) -> bool {
    l.data.join("mysql.ibd").is_file()
}

fn fwd(p: &Path) -> String {
    p.display().to_string().replace('\\', "/")
}

pub fn render_ini(l: &Layout) -> String {
    format!(
        r#"# Generated by Zefaro — rewritten on every start, do not edit.
[mysqld]
basedir="{base}"
datadir="{data}"
port={port}
bind-address=127.0.0.1
# The X Protocol would listen on 33060 as well; nothing in Zefaro uses it.
mysqlx=OFF
# Log times in this computer's time zone, like the other logs.
log_timestamps=SYSTEM
# Modest memory use for a development machine.
innodb_buffer_pool_size=128M
performance_schema=OFF
# Large rows and long multi-row INSERTs in big dumps.
max_allowed_packet=1G
# Flush the redo log about once a second instead of at every commit: much
# faster imports, and a power cut could lose the last second of writes. Fine
# for local development, never for a production server.
innodb_flush_log_at_trx_commit=2

[client]
host=127.0.0.1
port={port}
"#,
        base = fwd(&l.base),
        data = fwd(&l.data),
        port = l.port,
    )
}

/// Create the system tables (once). `--initialize-insecure` gives
/// root@localhost no password; the server only listens on 127.0.0.1.
fn initialize(l: &Layout) -> AppResult<()> {
    if l.data.is_dir() && fs::read_dir(&l.data)?.next().is_some() {
        let data = l.data.display();
        return Err(AppError::msg(crate::tr!(
            format!("{data} has files in it but no MySQL system tables. Move the folder somewhere else and start MySQL again."),
            format!("{data} berisi file tetapi tidak punya tabel sistem MySQL. Pindahkan folder itu ke tempat lain, lalu mulai MySQL lagi.")
        )));
    }
    if let Some(parent) = l.data.parent() {
        fs::create_dir_all(parent)?;
    }
    // --defaults-file must come first.
    process::run(process::command(l.bin("mysqld.exe")).args([
        format!("--defaults-file={}", l.conf.display()),
        "--initialize-insecure".into(),
        "--console".into(),
    ]))
    .map(|_| ())
    .map_err(|e| {
        AppError::msg(crate::tr!(
            format!("Zefaro couldn't create the MySQL data folder: {e}"),
            format!("Zefaro tidak dapat membuat folder data MySQL: {e}")
        ))
    })
}

/// Install on first use, write my.ini, and create the data folder once.
/// Serialized, so two starts at once can't install or initialise twice.
pub fn prepare(l: &Layout, scratch: &Path, keep_zip: bool) -> AppResult<()> {
    archive::exclusive(&l.base, || {
        if !installed(l) {
            ARCHIVE.install_filtered(&l.base, scratch, keep_zip, wanted)?;
        }
        if let Some(dir) = l.conf.parent() {
            fs::create_dir_all(dir)?;
        }
        fs::write(&l.conf, render_ini(l))?;
        if !initialized(l) {
            initialize(l)?;
        }
        Ok(())
    })
}

/// Connection options for MySQL's own clients (mysql, mysqladmin).
fn client_args(port: u16) -> Vec<String> {
    vec!["--host=127.0.0.1".into(), format!("--port={port}"), "--user=root".into()]
}

pub fn spec(l: &Layout) -> Spec {
    let mut stop: Vec<std::ffi::OsString> = client_args(l.port).into_iter().map(Into::into).collect();
    stop.push("shutdown".into());
    Spec {
        id: SERVICE_ID.into(),
        program: l.bin("mysqld.exe"),
        // --console sends the server log to stderr, i.e. into mysql.log.
        args: vec![format!("--defaults-file={}", l.conf.display()).into(), "--console".into()],
        cwd: l.base.clone(),
        env: Vec::new(),
        log: l.log.clone(),
        port: l.port,
        probe: Probe::Tcp,
        // A clean shutdown flushes InnoDB instead of forcing crash recovery.
        stop: Some((l.bin("mysqladmin.exe"), stop)),
    }
}

/// Run SQL as root through MySQL's own client; returns tab-separated rows.
pub fn query(l: &Layout, sql: &str) -> AppResult<String> {
    process::run(
        process::command(l.bin("mysql.exe"))
            .args(client_args(l.port))
            .args(["--batch", "--skip-column-names", "-e", sql]),
    )
    .map_err(|e| AppError::msg(format!("MySQL: {e}")))
}

/// Does a database exist?
pub fn database_exists(l: &Layout, name: &str) -> AppResult<bool> {
    let sql = format!("SELECT 1 FROM information_schema.SCHEMATA WHERE SCHEMA_NAME = '{}'", name.replace('\'', "''"));
    Ok(query(l, &sql)?.trim() == "1")
}

/// Create a database (utf8mb4, MySQL's default collation).
pub fn create_database(l: &Layout, name: &str) -> AppResult<()> {
    query(l, &format!("CREATE DATABASE `{}`", name.replace('`', "``"))).map(|_| ())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::engine::supervisor::{port_open, Supervisor};

    fn layout(root: &Path, port: u16) -> Layout {
        Layout {
            base: root.join("mysql"),
            data: root.join("data"),
            conf: root.join("conf").join("my.ini"),
            log: root.join("mysql.log"),
            port,
        }
    }

    #[test]
    fn ini_and_spec_stay_on_loopback_beside_mariadb() {
        let l = Layout {
            base: PathBuf::from(r"C:\zefaro\bin\mysql"),
            data: PathBuf::from(r"C:\zefaro\data\mysql"),
            conf: PathBuf::from(r"C:\zefaro\mysql\my.ini"),
            log: PathBuf::from(r"C:\zefaro\logs\mysql.log"),
            port: PORT,
        };
        assert_ne!(PORT, crate::engine::mariadb::PORT);
        let ini = render_ini(&l);
        assert!(ini.contains("bind-address=127.0.0.1"));
        assert!(ini.contains("port=3307"));
        assert!(ini.contains("mysqlx=OFF"));
        assert!(ini.contains(r#"datadir="C:/zefaro/data/mysql""#));
        let spec = spec(&l);
        assert_eq!(spec.args[0], r"--defaults-file=C:\zefaro\mysql\my.ini", "must be the first argument");
        let (exe, args) = spec.stop.unwrap();
        assert!(exe.ends_with("mysqladmin.exe"));
        assert!(args.iter().any(|a| a == "--port=3307") && args.last().unwrap() == "shutdown");
    }

    #[test]
    fn unpacks_the_server_and_clients_without_debug_files() {
        for keep in ["bin/mysqld.exe", "bin/mysqladmin.exe", "bin/libcrypto-3-x64.dll", "lib/plugin/auth_ldap.dll", "share/english/errmsg.sys"] {
            assert!(wanted(Path::new(keep)), "{keep}");
        }
        for skip in ["bin/mysqld.pdb", "lib/mysqlclient.lib", "lib/mecab/dic/ipadic_utf-8/sys.dic", "lib/plugin/debug/x.dll", "include/mysql.h", "docs/INFO_SRC"] {
            assert!(!wanted(Path::new(skip)), "{skip}");
        }
    }

    /// Installs MySQL from the pinned zip into a temp folder (the zip is kept
    /// in `ZEFARO_MYSQL_ZIP_DIR`, or downloaded there), initialises it, starts
    /// it on a spare port, creates a database and stops it cleanly.
    #[test]
    #[ignore]
    fn live_installs_starts_and_stops_mysql() {
        let root = std::env::temp_dir().join("zefaro-mysql-test");
        let _ = fs::remove_dir_all(&root);
        fs::create_dir_all(&root).unwrap();
        let scratch = std::env::var_os("ZEFARO_MYSQL_ZIP_DIR").map(PathBuf::from).unwrap_or_else(|| root.join("dl"));
        let l = layout(&root, 53307);
        prepare(&l, &scratch, true).unwrap();
        assert!(installed(&l));
        assert!(!l.base.join("include").exists(), "headers were unpacked");
        assert!(!l.base.join("bin").join("mysqld.pdb").exists(), "debug symbols were unpacked");
        assert!(l.data.join("mysql.ibd").is_file());

        let sup = Supervisor::default();
        sup.start(spec(&l)).unwrap();
        assert!(port_open(53307));
        assert!(!port_open(33060), "X Protocol listening");
        assert_eq!(query(&l, "SELECT VERSION()").unwrap().trim(), VERSION);
        assert!(!database_exists(&l, "zefaro_test").unwrap());
        create_database(&l, "zefaro_test").unwrap();
        assert!(database_exists(&l, "zefaro_test").unwrap());
        // Laravel connects over TCP to 127.0.0.1 as root without a password.
        assert_eq!(query(&l, "SELECT CURRENT_USER()").unwrap().trim(), "root@localhost");
        // The `mysql` shim is MariaDB's client; with --port it reaches MySQL
        // too, given the folder with its caching_sha2_password plugin.
        let mariadb_base = crate::engine::mariadb::Layout::standard().base;
        if mariadb_base.join("bin").join("mariadb.exe").is_file() {
            let out = process::run(
                process::command(mariadb_base.join("bin").join("mariadb.exe"))
                    .arg(format!("--plugin-dir={}", mariadb_base.join("lib").join("plugin").display()))
                    .args(["--host=127.0.0.1", "--port=53307", "--user=root", "--skip-ssl", "-N", "-e", "SELECT 40+2"]),
            );
            assert_eq!(out.unwrap().trim(), "42");
        }

        sup.stop(SERVICE_ID).unwrap();
        assert!(!port_open(53307));
        let log = fs::read_to_string(&l.log).unwrap();
        assert!(log.contains("Shutdown complete"), "{log}");
        let _ = fs::remove_dir_all(&root);
    }
}
