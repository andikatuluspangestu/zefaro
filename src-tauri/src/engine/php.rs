    #[test]
    fn parses_nts_x64_builds_newest_first_and_skips_old_lines() {
        let json = serde_json::json!({
            "7.3": { "version": "7.3.33", "nts-vc15-x64": { "zip": { "path": "php-7.3.33.zip" } } },
            "7.4": { "version": "7.4.33",
                     "ts-vc15-x64":  { "zip": { "path": "ts.zip" } },
                     "nts-vc15-x86": { "zip": { "path": "x86.zip" } },
                     "nts-vc15-x64": { "zip": { "path": "php-7.4.33-nts-Win32-vc15-x64.zip",
                                                "size": "24.92MB", "sha256": "ABC123" } } },
            "8.5": { "version": "8.5.11",
                     "nts-vs17-x64": { "zip": { "path": "php-8.5.11-nts-Win32-vs17-x64.zip" } } },
            "8.10": { "version": "8.10.0",
                      "nts-vs18-x64": { "zip": { "path": "php-8.10.0.zip" } } }
        });
        let r = parse_releases(&json);
        let minors: Vec<_> = r.iter().map(|r| r.minor.as_str()).collect();
        // Numeric, not lexical, ordering: 8.10 > 8.5.
        assert_eq!(minors, ["8.10", "8.5", "7.4"]);
        let php74 = &r[2];
        assert_eq!(php74.file, "php-7.4.33-nts-Win32-vc15-x64.zip");
        assert_eq!(php74.sha256.as_deref(), Some("abc123"));
        assert_eq!(php74.size.as_deref(), Some("24.92MB"));
        assert_eq!(r[1].sha256, None);
    }

